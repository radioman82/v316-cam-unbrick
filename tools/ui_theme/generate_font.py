"""Generate the small anti-aliased UI glyph atlas from the existing Windows font."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont


def generate(destination):
    glyphs, runs = [], []
    codes = [ord('?')] + [c for c in range(32, 256) if c != ord('?') and not 127 <= c < 160]
    codes += [0x2026, 0x2190, 0x2191, 0x2193, 0x25b2, 0x25bc]
    for code in codes:
        for large in (0, 1):
            f = ImageFont.truetype('C:/Windows/Fonts/segoeuib.ttf' if large else 'C:/Windows/Fonts/segoeui.ttf', 16 if large else 14)
            advance = round(f.getlength(chr(code)))
            w, h = max(1, advance+1), 20 if large else 18
            im = Image.new('L', (w,h)); ImageDraw.Draw(im).text((0,-2),chr(code),font=f,fill=255)
            start = len(runs)
            for y in range(h):
                row = [(im.getpixel((x,y))*3+127)//255 for x in range(w)]
                x=0
                while x<w:
                    end=x+1
                    while end<w and row[end]==row[x] and end-x<64:end+=1
                    runs.append((row[x]<<6)|(end-x-1));x=end
            glyphs.append((code,large,w,h,advance,start))
    out = ['/* Generated by generate_font.py; four coverage levels, row RLE. */',
           'typedef struct { unsigned short code; unsigned char large,width,height,advance; unsigned offset; } Glyph;',
           'static const unsigned char font_runs[]={']
    for i in range(0,len(runs),30):out.append(','.join(map(str,runs[i:i+30]))+',')
    out += ['};','static const Glyph glyphs[]={']
    out += ['{'+','.join(map(str,g))+'},' for g in glyphs]
    out += ['};']
    destination.write_text('\n'.join(out)+'\n')
    return len(runs)


if __name__=='__main__':
    print(generate(Path(__file__).with_name('font.h')))
